const LANG_KEY = 'ldsshmanager-lang';

import {ref} from 'vue'
export const currentLang = ref(getStoredLang());

function getStoredLang(): string {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v && LANGS.some(([c]) => c === v)) return v;
  } catch (e) { /* ignore */ }
  return DEFAULT_LANG;
}

export function getLang(): string { return currentLang.value; }

export function setLang(code: string) {
  if (!LANGS.some(([c]) => c === code)) code = DEFAULT_LANG;
  currentLang.value = code;
  try { localStorage.setItem(LANG_KEY, code); } catch (e) { /* ignore */ }
  document.documentElement.lang = code;
  document.documentElement.dataset.lang = code;
  window.dispatchEvent(new CustomEvent('ldsshmanager:langchange', { detail: { lang: code } }));
}

export function initI18n() {
  const code = getLang();
  document.documentElement.lang = code;
  document.documentElement.dataset.lang = code;
}

export function t(key: string, vars?: Record<string, string | number>): string {
  const lang = getLang();
  let s = key;
  if (lang !== DEFAULT_LANG) {
    const d = DICT[lang];
    if (d && d[key] != null) s = d[key];
  }
  if (vars && s.indexOf('{') >= 0) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split('{' + k + '}').join(String(v == null ? '' : v));
    }
  }
  return s;
}

export function langLabel(code: string): string {
  const hit = LANGS.find(([c]) => c === code);
  return hit ? hit[1] : code;
}
